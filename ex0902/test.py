# 3. 함수와 사칙연산
# ==========================================

# def 함수 정의
# 매개변수 a,b,c,d 를 받아 사칙 연산 한 값을 반
def f1(a):
    return a + 100
def f2(b):
    return b - 100
def f3(c):
    return c * 5
def f4(d):
    return d/5  
  
# 함수 호출 및 결과 출력
print(f1(5))
print(f2(5))
print(f3(5))
print(f4(5))