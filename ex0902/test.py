# 2. 리스트와 반복문
# ==========================================

# 여러 개의 데이터를 하나의 리스트로 저장
list = ['파이썬 기본 문법', '클래스', '데코레이터', '예외 처리', '로깅']

# 공통으로 적용할 시간을 변수에 저장
y1 = 8

# for문을 이용해 리스트의 요소를 하나씩 꺼냄
for i in list:
    print(i, y1, sep=', 시간:')   # 리스트에서 꺼낸 내용과 시간을 출력
  

