# ==========================================
# NumPy 라이브러리 사용하여 배열 생성
# ==========================================

import numpy as np  # NumPy 라이브러리를 불러오고 np라는 이름으로 사용

arr = np.array([1,2,3,4,5]) # np.array()를 이용하여 1~5까지의 값을 가진 배열 생성

print(arr) # 생성된 배열 출력

print(type(arr)) # arr의 자료형(type) 확인